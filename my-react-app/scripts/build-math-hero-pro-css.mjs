#!/usr/bin/env node
/**
 * Builds src/games/math-hero-pro/styles/math-hero-pro.css: Math Hero Pro's Tailwind styles, compiled
 * ahead of time (Bulbuli doesn't use Tailwind) and scoped to #math-hero-pro-root, exactly like
 * VoxelCraft's (see build-voxelcraft-css.mjs for what scoping does and why).
 *
 *   npm run build:math-hero-pro-css                                   compile with the Tailwind CLI (npx), then scope
 *   node scripts/build-math-hero-pro-css.mjs --from <tailwind-output.css>   scope an existing build
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { compileTailwind, scopeCss } from './build-voxelcraft-css.mjs'

const ROOT = '#math-hero-pro-root'
const KEYFRAME_PREFIX = 'mhp-'

const here = path.dirname(fileURLToPath(import.meta.url))
const stylesDir = path.resolve(here, '../src/games/math-hero-pro/styles')
const input = path.join(stylesDir, 'tailwind.input.css')
const output = path.join(stylesDir, 'math-hero-pro.css')

const fromIdx = process.argv.indexOf('--from')
const raw = fromIdx > -1 ? readFileSync(process.argv[fromIdx + 1], 'utf8') : compileTailwind(input)
const banner =
  '/* GENERATED by scripts/build-math-hero-pro-css.mjs from tailwind.input.css. Do not edit by hand.\n' +
  `   Every rule is scoped to ${ROOT}; see scripts/build-voxelcraft-css.mjs for why. */\n`
writeFileSync(output, banner + scopeCss(raw, { root: ROOT, keyframePrefix: KEYFRAME_PREFIX }).trim() + '\n')
console.log(`math-hero-pro.css written (${(readFileSync(output).length / 1024).toFixed(1)} KB)`)
