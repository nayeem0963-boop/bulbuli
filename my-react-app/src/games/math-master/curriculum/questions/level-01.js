const isPrime = (n) => {
  if (!Number.isInteger(n) || n < 2) return false
  for (let d = 2; d * d <= n; d += 1) if (n % d === 0) return false
  return true
}
const gcd = (a, b) => (b === 0 ? a : gcd(b, a % b))
const lcm = (a, b) => (a * b) / gcd(a, b)

